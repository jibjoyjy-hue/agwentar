function renderGuide() {
  const body = document.getElementById("guideModalBody");
  if (!body) return;
  body.innerHTML = `
    <div class="premium-hero"><div class="premium-crown">📖</div>
      <div class="premium-title">คู่มือการใช้</div>
      <div class="premium-sub">แตะหัวข้อเพื่อดูรายละเอียด</div></div>
    <div class="guide-list">${GUIDE_SECTIONS.map((s, i) => `
      <details class="guide-item"${i === 0 ? " open" : ""}>
        <summary><span class="guide-ico">${s.icon}</span><span>${s.title}</span></summary>
        <div class="guide-body">${s.body}</div>
      </details>`).join("")}
    </div>
    <button type="button" class="premium-cta" onclick="closeGuide()">เข้าใจแล้ว</button>`;
}

function openGuide() {
  const m = document.getElementById("guideModal");
  if (!m) return;
  renderGuide();
  m.style.display = "flex";
}
function closeGuide() {
  const m = document.getElementById("guideModal");
  if (m) m.style.display = "none";
}
document.addEventListener("keydown", e => { if (e.key === "Escape") closeGuide(); });
